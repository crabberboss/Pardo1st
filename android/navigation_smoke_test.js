const fs=require('fs'),vm=require('vm'),assert=require('assert');
const code=fs.readFileSync('app/src/main/assets/navigation.js','utf8');
new vm.Script(code);
let view='home',gen='project',openedProject='';
const classes=new Set();
const body={classList:{contains:key=>classes.has(key),add:key=>classes.add(key),remove:key=>classes.delete(key)}};
const sheets={readerImageGallery:{style:{display:'none'}},chatEditPanel:{classList:{contains:()=>true}},chatMenu:{classList:{contains:()=>true}},chatSessions:{classList:{contains:()=>true}}};
const context=vm.createContext({window:{tab:name=>{view=name},genPage:name=>{gen=name},genOpenWorkStatus:id=>{openedProject=id}},document:{body,querySelector:selector=>selector==='section.view.active'?{id:'view-'+view}:selector.includes('.gen-flow')?{id:'genNav'+gen[0].toUpperCase()+gen.slice(1)}:null,addEventListener(){}},$:id=>sheets[id],readerCloseImages:()=>sheets.readerImageGallery.style.display='none',readerCloseCatalog:()=>classes.delete('reader-catalog-open'),closeMessageEditor(){},toggleChatMenu(){},toggleChatSessions(){},readerReturnToBook:()=>{view='reader'},mobileReader:()=>{view='reader-library'}});
vm.runInContext(code,context);
context.window.tab('library');context.window.tab('chat');
assert(context.window.appHandleBack());assert.equal(view,'library');
assert(context.window.appHandleBack());assert.equal(view,'home');
assert.equal(context.window.appHandleBack(),false);
context.window.tab('reader-library');context.window.tab('reader');
classes.add('reader-menu-open');assert(context.window.appHandleBack());assert.equal(view,'reader');assert(!classes.has('reader-menu-open'));
classes.add('reader-catalog-open');assert(context.window.appHandleBack());assert.equal(view,'reader');assert(!classes.has('reader-catalog-open'));
assert(context.window.appHandleBack());assert.equal(view,'reader-library');
context.window.tab('generation');context.window.genPage('run');context.window.genPage('text');
assert(context.window.appHandleBack());assert.equal(gen,'run');
assert(context.window.appHandleBack());assert.equal(gen,'project');
context.window.appOpenWorkStatus('generation');assert.equal(view,'generation');assert.equal(gen,'run');
context.window.appOpenWorkStatus('generation','active-project');assert.equal(openedProject,'active-project');
console.log('Android back navigation smoke tests passed');
